const asciiBlock = 64

proc validateUtf8*[T: byte | char](text: openArray[T]): bool =
  var state = 0
  let n = text.len
  var i = 0
  while i + asciiBlock <= n:
    if state == UTF8_ACCEPT:
      var res = 0'u8
      for j in 0 ..< asciiBlock:
        res = res or uint8(text[i + j])
      if res <= 0x7F'u8:
        i += asciiBlock
        continue
    for j in 0 ..< asciiBlock:
      let x = utf8Table[text[i + j].int].int
      state = utf8Table[256 + state*16 + x].int
    i += asciiBlock
  while i < n:
    let x = utf8Table[text[i].int].int
    state = utf8Table[256 + state*16 + x].int
    inc i
  state == UTF8_ACCEPT
